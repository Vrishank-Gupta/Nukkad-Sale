const DICTS: Record<Lang, Dict> = { en, hi }

export function getLang(c: Context): Lang {
  const cookie = getCookie(c, 'lang')
  if (cookie === 'hi' || cookie === 'en') return cookie
  return /^hi\b/i.test(c.req.header('Accept-Language') ?? '') ? 'hi' : 'en'
}

export const tr = (c: Context): Dict => DICTS[getLang(c)]
export const dictFor = (lang: Lang): Dict => DICTS[lang]
